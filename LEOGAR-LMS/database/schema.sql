CREATE TABLE IF NOT EXISTS users(
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, phone TEXT NOT NULL,
 email TEXT NOT NULL UNIQUE, college TEXT NOT NULL, password_hash TEXT NOT NULL,
 created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS video_progress(
 user_id INTEGER NOT NULL REFERENCES users(id), course_id TEXT NOT NULL, video_idx INTEGER NOT NULL,
 completed_at TEXT DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,course_id,video_idx));
CREATE TABLE IF NOT EXISTS attempts(
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id), course_id TEXT NOT NULL, video_idx INTEGER NOT NULL DEFAULT 0,
 score INTEGER NOT NULL, passed INTEGER NOT NULL, created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS reports(
 report_id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), course_id TEXT NOT NULL, video_idx INTEGER NOT NULL DEFAULT 0,
 score INTEGER NOT NULL, issued_at TEXT DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,course_id));
